import os
import csv
from datetime import datetime
from typing import List, Dict, Any
from io import StringIO, BytesIO

def generate_csv_report(violations: List[Dict[str, Any]]) -> str:
    """
    Generates CSV formatted string of violation records.
    """
    output = StringIO()
    writer = csv.writer(output)

    # Headers
    writer.writerow([
        "ID",
        "Violation Type",
        "Tier",
        "Video Timestamp (s)",
        "Wall Clock Timestamp",
        "Track ID",
        "Confidence",
        "Review Status",
        "Reviewer",
        "Review Notes",
        "Source File",
        "Scene Config"
    ])

    for v in violations:
        writer.writerow([
            v.get("id", ""),
            v.get("violation_type", ""),
            v.get("tier", ""),
            v.get("video_timestamp", ""),
            v.get("wall_clock_timestamp", ""),
            v.get("track_id", ""),
            v.get("confidence", ""),
            v.get("review_status", ""),
            v.get("reviewer_name", ""),
            v.get("review_notes", ""),
            v.get("source_file", ""),
            v.get("scene_config_name", "")
        ])

    return output.getvalue()


def generate_pdf_report(violations: List[Dict[str, Any]], title: str = "Traffic Violation Summary Report") -> bytes:
    """
    Generates a structured PDF report summarizing violations and human review audits.
    """
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.lib import colors
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

        buffer = BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
        elements = []
        styles = getSampleStyleSheet()

        # Title
        title_style = ParagraphStyle(
            'ReportTitle',
            parent=styles['Heading1'],
            fontSize=18,
            leading=22,
            textColor=colors.HexColor('#1E293B'),
            spaceAfter=6
        )
        elements.append(Paragraph(title, title_style))

        # Disclaimer
        disclaimer_style = ParagraphStyle(
            'Disclaimer',
            parent=styles['Italic'],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor('#DC2626'),
            spaceAfter=14
        )
        elements.append(Paragraph(
            "<b>LEGAL NOTICE:</b> This report is generated by a Decision-Support System. "
            "All listed incidents are possible violations requiring human verification and do not constitute legal proof.",
            disclaimer_style
        ))

        # Summary Metrics
        total = len(violations)
        confirmed = sum(1 for v in violations if v.get("review_status") == "CONFIRMED")
        pending = sum(1 for v in violations if v.get("review_status") == "PENDING")
        rejected = sum(1 for v in violations if v.get("review_status") == "REJECTED")

        summary_text = f"<b>Generated:</b> {datetime.now().strftime('%Y-%m-%d %H:%M:%S')} | <b>Total Detections:</b> {total} | <b>Confirmed:</b> {confirmed} | <b>Pending Review:</b> {pending} | <b>Rejected:</b> {rejected}"
        elements.append(Paragraph(summary_text, styles['Normal']))
        elements.append(Spacer(1, 14))

        # Table Data
        table_data = [["ID", "Violation", "Tier", "Time(s)", "Track", "Conf", "Status", "Reviewer"]]
        for v in violations[:60]:  # Limit rows in PDF preview
            table_data.append([
                str(v.get("id", "")),
                str(v.get("violation_type", "")).replace("_", " "),
                str(v.get("tier", "")),
                f"{v.get('video_timestamp', 0):.1f}s",
                str(v.get("track_id", "")),
                f"{v.get('confidence', 0):.2f}",
                str(v.get("review_status", "PENDING")),
                str(v.get("reviewer_name", "") or "-")
            ])

        t = Table(table_data, colWidths=[30, 110, 45, 55, 45, 45, 75, 80])
        t.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#2563EB')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, 0), 9),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 6),
            ('BACKGROUND', (0, 1), (-1, -1), colors.HexColor('#F8FAFC')),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
            ('FONTSIZE', (0, 1), (-1, -1), 8),
        ]))
        elements.append(t)

        doc.build(elements)
        buffer.seek(0)
        return buffer.getvalue()
    except Exception as e:
        # Fallback simple text-based representation if reportlab encounters layout issue
        return f"PDF generation error: {str(e)}".encode("utf-8")
